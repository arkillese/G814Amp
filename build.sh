#!/bin/bash
# Builds G814Amp.kext, probe-tool and set-output into ./build
set -euo pipefail
cd "$(dirname "$0")"
SDK=$(xcrun --sdk macosx --show-sdk-path)
KH="$SDK/System/Library/Frameworks/Kernel.framework/Headers"
OUT=build/G814Amp.kext/Contents
rm -rf build && mkdir -p "$OUT/MacOS"

# Embed the Cirrus firmware files (unmodified, see firmware/LICENSE.cirrus) as C arrays.
FW=firmware
{
  echo "// Generated by build.sh from $FW/ - Cirrus Logic firmware, see $FW/LICENSE.cirrus"
  emb() { xxd -i -n "$1" "$FW/$2" | sed 's/^unsigned char/static const unsigned char/; s/^unsigned int/static const unsigned int/'; }
  emb fw_wmfw             halo_cspl_RAM_revB2_29.63.1.wmfw
  emb fw_bin_spkid0_left  cs35l41-dsp1-spk-prot-10431ccf-spkid0-l0.bin
  emb fw_bin_spkid0_right cs35l41-dsp1-spk-prot-10431ccf-spkid0-r0.bin
  emb fw_bin_spkid1_left  cs35l41-dsp1-spk-prot-10431ccf-spkid1-l0.bin
  emb fw_bin_spkid1_right cs35l41-dsp1-spk-prot-10431ccf-spkid1-r0.bin
} > build/Firmware.h

CFLAGS=(-arch x86_64 -isysroot "$SDK" -mkernel -nostdinc -I"$KH" -Ibuild -DKERNEL -DKERNEL_PRIVATE -DDRIVER_PRIVATE
        -DAPPLE -DNeXT -O2 -Wall -Wno-unused-private-field -Wno-deprecated-declarations -mmacosx-version-min=14.0)
xcrun clang -c "${CFLAGS[@]}" -std=c11 kmod_info.c -o build/kmod_info.o
xcrun clang++ -c "${CFLAGS[@]}" -std=gnu++17 -fapple-kext -fno-rtti -fno-exceptions -fno-builtin \
    G814Amp.cpp -o build/G814Amp.o
xcrun clang++ -arch x86_64 -isysroot "$SDK" -mmacosx-version-min=14.0 -nostdlib -Xlinker -kext \
    -lkmodc++ -lkmod -lcc_kext build/kmod_info.o build/G814Amp.o -o "$OUT/MacOS/G814Amp"
cp Info.plist "$OUT/Info.plist"
codesign -f -s - build/G814Amp.kext

xcrun clang -arch x86_64 -O2 -Wall probe-tool.c -framework IOKit -framework CoreFoundation -o build/probe-tool
xcrun clang -O2 -Wall tools/set-output.c -framework CoreAudio -framework CoreFoundation -o build/set-output
echo "built: build/G814Amp.kext build/probe-tool build/set-output"
